-- Optimistic locking: two inventory results for one order must not both win.
ALTER TABLE orders ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

-- One row per status change, for GET /orders/{id}/timeline.
CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID        NOT NULL REFERENCES orders (id),
    status      VARCHAR(20) NOT NULL,
    event_id    UUID,                  -- event published (PENDING) or consumed (CONFIRMED/CANCELLED)
    event_type  VARCHAR(50),
    reason      TEXT,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_order_status_history_order_id ON order_status_history (order_id);

-- Orders created before this migration get their initial PENDING entry (event id unknown).
INSERT INTO order_status_history (order_id, status, occurred_at)
SELECT id, 'PENDING', created_at FROM orders;

-- Idempotent consumer for inventory.reserved / inventory.rejected.
CREATE TABLE processed_events (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL
);
